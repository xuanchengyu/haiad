<template>
  <div class="mode-selection">
    <NavBar 
      :showBack="true"
    />
    <main class="main-content">
      <div class="modes-container">
        <div class="mode-card" @click="selectMode('human-only')">
          <div class="mode-icon">👤</div>
          <h2>Human-Only Writing</h2>
          <p>Write AD scripts entirely by yourself</p>
          <ul>
            <li>No AI assistance</li>
          </ul>
        </div>

        <div class="mode-card" @click="selectMode('ai-assisted')">
          <div class="mode-icon">🤖</div>
          <h2>AI-assisted Writing</h2>
          <p>Edit scripts pre-generated by AI</p>
          <ul>
            <li>AI generates initial script</li>
            <li>Freedom to modify</li>
          </ul>
        </div>

        <div class="mode-card" @click="selectMode('collaborative')">
          <div class="mode-icon">👥</div>
          <h2>AD Copilot</h2>
          <p>Collaborate with AI to edit scripts</p>
          <ul>
            <li>AI suggestions</li>
            <li>Interactive collaboration</li>
            <li>Human in the loop</li>
          </ul>
        </div>
      </div>
    </main>
  </div>
</template>

<script>
import NavBar from '@/components/NavBar.vue'

export default {
  name: 'ModeSelection',
  components: {
    NavBar
  },
  data() {
    return {
      videoId: this.$route.params.id
    }
  },
  mounted() {
    console.log('当前视频ID:', this.videoId); // 添加调试日志
  },
  methods: {
    selectMode(mode) {
      console.log('选择模式:', mode, '视频ID:', this.videoId);
      try {
        let path = '';
        switch(mode) {
          case 'human-only':
            path = `/human-only/${this.videoId}`;
            break;
          case 'ai-assisted':
            path = `/ai-assisted/${this.videoId}`;
            break;
          case 'collaborative':
            path = `/collaborative/${this.videoId}`;
            break;
        }
        this.$router.push(path);
      } catch (error) {
        console.error('路由跳转失败:', error);
      }
    },
    goBack() {
      this.$router.push('/');
    }
  }
}
</script>

